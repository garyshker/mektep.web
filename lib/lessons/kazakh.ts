import type { Lesson, Question } from './types'

function _sfl<T>(arr: T[]): T[] {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

function _mc(prompt: string, correct: string, wrong: [string, string, string], big = false): Question {
  const opts = _sfl([correct, ...wrong])
  // When `big`, the prompt is a Kazakh word/number — attach audio so the lesson
  // shows a 🔊 button. Russian-prompt questions (big=false) get no audio.
  return { kind: 'mc', prompt, big, options: opts, answer: opts.indexOf(correct), audio: big ? prompt : undefined }
}

// Kazakh phrase → Russian meaning, with audio (not rendered big)
function _mcPhrase(kk: string, ru: string, wrong: [string, string, string]): Question {
  const opts = _sfl([ru, ...wrong])
  return { kind: 'mc', prompt: kk, options: opts, answer: opts.indexOf(ru), audio: kk }
}

// Connect Kazakh words with their translations
function _pairs(ru: string, kk: string, pairs: { a: string; b: string }[]): Question {
  return { kind: 'pairs', promptByLang: { kk, ru, en: ru }, pairs }
}

// Sort Kazakh words into two groups
function _match(ru: string, kk: string, groupsRu: [string, string], groupsKk: [string, string],
  items: { text: string; group: number }[]): Question {
  return {
    kind: 'match',
    promptByLang: { kk, ru, en: ru },
    groupsByLang: { kk: groupsKk, ru: groupsRu, en: groupsRu },
    items: _sfl(items),
  }
}

function _tap(ru: string, kk: string, correct: string[], wrong: string[]): Question {
  const items = _sfl([
    ...correct.map(e => ({ e, ok: true })),
    ...wrong.map(e => ({ e, ok: false })),
  ])
  return {
    kind: 'tap',
    promptByLang: { kk, ru, en: ru },
    words: items.map(x => x.e),
    correctIdxs: items.map((x, i) => x.ok ? i : -1).filter(i => i >= 0),
  }
}

function _word(ru: string, kk: string, correct: string, wrong: [string, string, string]): Question {
  const opts = _sfl([correct, ...wrong])
  return {
    kind: 'word',
    storyByLang: { kk, ru, en: ru },
    options: opts,
    answer: opts.indexOf(correct),
  }
}

