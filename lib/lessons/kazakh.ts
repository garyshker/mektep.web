import type { Lesson, Question } from './types'

function _sfl<T>(arr: T[]): T[] {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

function _mc(prompt: string, correct: string, wrong: [string, string, string], big = false): Question {
  const opts = _sfl([correct, ...wrong])
  return { kind: 'mc', prompt, big, options: opts, answer: opts.indexOf(correct) }
}

function _tap(ru: string, kk: string, correct: string[], wrong: string[]): Question {
  const items = _sfl([
    ...correct.map(e => ({ e, ok: true })),
    ...wrong.map(e => ({ e, ok: false })),
  ])
  return {
    kind: 'tap',
    promptByLang: { kk, ru, en: ru },
    words: items.map(x => x.e),
    correctIdxs: items.map((x, i) => x.ok ? i : -1).filter(i => i >= 0),
  }
}

